import { describe, expect, it } from 'vitest';
import {
  COOKBOOK_CHAPTERS,
  COOKBOOK_ID,
  COOKBOOK_TITLE,
  FRONT_MATTER,
  BACK_MATTER,
  TARGET_RECIPE_COUNT,
  RECIPES_PER_CHAPTER,
  getChapterById,
  getChapterByOrder,
  getChapterIds,
  getTotalTargetRecipeCount,
} from './structure';
