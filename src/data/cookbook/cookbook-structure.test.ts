describe('V3C.44A evidence rules', () => {
  it('defines historical claim rules', () => {
    expect(HISTORICAL_CLAIM_RULES.mustBeTraceableToResearch).toBe(true);
    expect(HISTORICAL_CLAIM_RULES.cannotPromoteWithoutEvidence).toBe(true);
    expect(HISTORICAL_CLAIM_RULES.uncertaintyMustBeVisible).toBe(true);
  });

  it('defines scripture rules', () => {
    expect(SCRIPTURE_RULES.mustUseKJVWording).toBe(true);
    expect(SCRIPTURE_RULES.mustCiteBookChapterVerse).toBe(true);
    expect(SCRIPTURE_RULES.cannotExtendBeyondRecordedText).toBe(true);
  });

  it('defines uncertainty rules', () => {
    expect(UNCERTAINTY_RULES.cannotConvertToCertainty).toBe(true);
    expect(UNCERTAINTY_RULES.unresolvedQuestionsMustBeDisclosed).toBe(true);
    expect(UNCERTAINTY_RULES.attestedMustBeDistinguishedFromInferred).toBe(
      true,
    );
  });

  it('defines reconstruction rules', () => {
    expect(RECONSTRUCTION_RULES.mustStateKnownVsUnknown).toBe(true);
    expect(RECONSTRUCTION_RULES.modernAdaptationsMustBeIdentified).toBe(true);
    expect(
      RECONSTRUCTION_RULES.cannotClaimExactAncientRecipesWithoutEvidence,
    ).toBe(true);
  });

  it('defines evidence prohibitions', () => {
    expect(EVIDENCE_PROHIBITIONS.length).toBeGreaterThan(0);
    expect(EVIDENCE_PROHIBITIONS).toContain('Fabricated citations');
    expect(EVIDENCE_PROHIBITIONS).toContain('Invented authorities');
    expect(EVIDENCE_PROHIBITIONS).toContain('Certainty inflation');
  });

  it('has combined evidence rules', () => {
    expect(EVIDENCE_RULES.historical).toBeDefined();
    expect(EVIDENCE_RULES.scripture).toBeDefined();
    expect(EVIDENCE_RULES.uncertainty).toBeDefined();
    expect(EVIDENCE_RULES.reconstruction).toBeDefined();
    expect(EVIDENCE_RULES.citation).toBeDefined();
    expect(EVIDENCE_RULES.modernAdaptation).toBeDefined();
  });
});

describe('V3C.44A recipe template', () => {
  it('defines recipe presentation sections', () => {
    expect(RECIPE_SECTIONS.length).toBeGreaterThan(0);
  });

  it('has required sections', () => {
    const required = RECIPE_SECTIONS.filter((s) => s.required);
    expect(required.length).toBeGreaterThan(0);
    expect(required.map((s) => s.id)).toContain('introduction');
    expect(required.map((s) => s.id)).toContain('ingredients');
    expect(required.map((s) => s.id)).toContain('method');
  });

  it('has correct section ordering', () => {
    const orders = RECIPE_SECTIONS.map((s) => s.order);
    const sorted = [...orders].sort((a, b) => a - b);
    expect(orders).toEqual(sorted);
  });

  it('defines presentation metadata', () => {
    expect(RECIPE_PRESENTATION_METADATA.requiredFields.length).toBeGreaterThan(
      0,
    );
    expect(
      RECIPE_PRESENTATION_METADATA.recommendedFields.length,
    ).toBeGreaterThan(0);
  });

  it('can get required fields for classification', () => {
    const inspired = getRequiredFieldsForClassification(
      'scripture-inspired-preparation',
    );
    expect(inspired).toContain('title');
    expect(inspired).toContain('ingredients');

    const reconstructed =
      getRequiredFieldsForClassification('modern-adaptation');
    expect(reconstructed).toContain('historicalContext');
    expect(reconstructed).toContain('evidenceNotes');
  });

  it('reconstructed recipes require more fields than inspired', () => {
    const inspired = getRequiredFieldsForClassification(
      'scripture-inspired-preparation',
    );
    const reconstructed =
      getRequiredFieldsForClassification('modern-adaptation');
    expect(reconstructed.length).toBeGreaterThan(inspired.length);
  });
});

describe('V3C.44A structural integrity', () => {
  it('chapter target recipes sum to total target', () => {
    const chapterTotal = COOKBOOK_CHAPTERS.reduce(
      (sum, ch) => sum + ch.targetRecipes,
      0,
    );
    expect(chapterTotal).toBe(TARGET_RECIPE_COUNT);
  });

  it('every chapter has a description', () => {
    for (const chapter of COOKBOOK_CHAPTERS) {
      expect(chapter.description).toBeTruthy();
      expect(chapter.description.length).toBeGreaterThan(0);
    }
  });

  it('every chapter has food categories', () => {
    for (const chapter of COOKBOOK_CHAPTERS) {
      expect(chapter.foodCategories.length).toBeGreaterThan(0);
    }
  });

  it('no chapter has duplicate food categories', () => {
    for (const chapter of COOKBOOK_CHAPTERS) {
      expect(new Set(chapter.foodCategories).size).toBe(
        chapter.foodCategories.length,
      );
    }
  });

  it('front matter has methodology referencing existing content', () => {
    const methodology = FRONT_MATTER.find((c) => c.id === 'methodology');
    expect(methodology?.existingContentSource).toBeTruthy();
  });

  it('back matter has auto-generated components with data sources', () => {
    const autoGenerated = BACK_MATTER.filter((c) => c.autoGenerated);
    for (const component of autoGenerated) {
      expect(component.dataSource).toBeTruthy();
    }
  });
});
