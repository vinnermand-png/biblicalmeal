describe('V3C.44A cookbook structure', () => {
  it('defines exactly one canonical cookbook ID', () => {
    expect(COOKBOOK_ID).toBe('biblicalmeal-cookbook-v1');
    expect(typeof COOKBOOK_ID).toBe('string');
  });

  it('defines a canonical cookbook title', () => {
    expect(COOKBOOK_TITLE).toBe(
      'Biblical Meals: Recipes Inspired by the Foods of the Bible',
    );
  });

  it('defines six chapters', () => {
    expect(COOKBOOK_CHAPTERS).toHaveLength(6);
  });

  it('has correct chapter ordering', () => {
    const orders = COOKBOOK_CHAPTERS.map((chapter) => chapter.order);
    expect(orders).toEqual([1, 2, 3, 4, 5, 6]);
  });

  it('has unique chapter IDs', () => {
    const ids = COOKBOOK_CHAPTERS.map((chapter) => chapter.id);
    expect(new Set(ids).size).toBe(ids.length);
  });

  it('has target recipe count of 30', () => {
    expect(TARGET_RECIPE_COUNT).toBe(30);
  });

  it('has 5 recipes per chapter target', () => {
    expect(RECIPES_PER_CHAPTER).toBe(5);
  });

  it('total target recipe count matches expected', () => {
    expect(getTotalTargetRecipeCount()).toBe(30);
  });

  it('can retrieve chapter by ID', () => {
    const chapter = getChapterById('grains-breads');
    expect(chapter).toBeDefined();
    expect(chapter?.title).toBe('Grains & Breads');
  });

  it('can retrieve chapter by order', () => {
    const chapter = getChapterByOrder(1);
    expect(chapter).toBeDefined();
    expect(chapter?.id).toBe('grains-breads');
  });

  it('can get all chapter IDs in order', () => {
    const ids = getChapterIds();
    expect(ids).toEqual([
      'grains-breads',
      'legumes-one-pot-meals',
      'fruits-preserves',
      'fish-seafood',
      'herbs-oils-seasonings',
      'feasts-gatherings',
    ]);
  });

  it('defines front matter components', () => {
    expect(FRONT_MATTER.length).toBeGreaterThan(0);
  });

  it('has correct front matter ordering', () => {
    const orders = FRONT_MATTER.map((component) => component.order);
    const sorted = [...orders].sort((a, b) => a - b);
    expect(orders).toEqual(sorted);
  });

  it('defines back matter components', () => {
    expect(BACK_MATTER.length).toBeGreaterThan(0);
  });

  it('has correct back matter ordering', () => {
    const orders = BACK_MATTER.map((component) => component.order);
    const sorted = [...orders].sort((a, b) => a - b);
    expect(orders).toEqual(sorted);
  });

  it('has methodology front matter referencing existing content', () => {
    const methodology = FRONT_MATTER.find((c) => c.id === 'methodology');
    expect(methodology).toBeDefined();
    expect(methodology?.existingContentSource).toBe(
      'src/content/articles/how-we-research.mdx',
    );
  });

  it('has auto-generated back matter components', () => {
    const autoGenerated = BACK_MATTER.filter((c) => c.autoGenerated);
    expect(autoGenerated.length).toBeGreaterThan(0);
  });
});

